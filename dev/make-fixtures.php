/**
 * dev/make-fixtures.php
 *
 * Generates small, valid sample books for the local dev stack.
 *
 * Run INSIDE the Nextcloud container -- it needs ext-zip and ext-gd, both of
 * which nextcloud:34-apache ships. The repo is bind-mounted, so the output
 * lands in ./dev/fixtures on the host. dev/seed.sh does this for you:
 *
 *   docker compose exec --user "$(id -u):$(id -g)" app php \
 *     /var/www/html/custom_apps/koreader_companion/dev/make-fixtures.php \
 *     /var/www/html/custom_apps/koreader_companion/dev/fixtures
 *
 * The EPUBs carry a full Dublin Core metadata block plus an embedded cover, so
 * they exercise BookService::parseEpubOPF() and the EPUB thumbnail path. The
 * PDF has a populated /Info dictionary for smalot/pdfparser.
 *
 * Note: the calibre:series meta below is deliberately included even though
 * parseEpubOPF() does not currently read it -- the app has a `series` column
 * and OPDS series facets, but no EPUB series extraction, so series is always
 * empty for EPUB today. The fixture is ready for when that is fixed.
 */

declare(strict_types=1);

$out = $argv[1] ?? __DIR__ . '/fixtures';
if (!is_dir($out) && !@mkdir($out, 0777, true)) {
